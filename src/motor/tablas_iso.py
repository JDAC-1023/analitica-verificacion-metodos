def _num(t: str) -> float | None:
    return None if t == "-" else float(t)


def _filas(texto: str) -> dict[int, list[float | None]]:
    salida = {}
    for linea in texto.strip().splitlines():
        partes = linea.split()
        salida[int(partes[0])] = [_num(x) for x in partes[1:]]
    return salida


COCHRAN = {p: {n: (v[2 * (n - 2)], v[2 * (n - 2) + 1]) for n in range(2, 7)} for p, v in _filas(_COCHRAN_TXT).items()}
GRUBBS = {p: tuple(v) for p, v in _filas(_GRUBBS_TXT).items()}
MANDEL = {1: _filas(_MANDEL_1_TXT), 5: _filas(_MANDEL_5_TXT)}


# ---------------------------------------------------------------- fórmulas teóricas
def cochran_formula(p: int, n: int, alfa: float) -> float:
    """C crítico = 1 / (1 + (p-1)/F), F = cuantil 1-α/p de F(n-1, (p-1)(n-1))."""
    v = n - 1
    f = stats.f.ppf(1 - alfa / p, v, (p - 1) * v)
    return 1 / (1 + (p - 1) / f)


def grubbs_formula(p: int, alfa: float) -> float:
    """G crítico (un extremo, criterio bilateral α/(2p)) = (p-1)/√p · √(t²/(p-2+t²))."""
    t = stats.t.ppf(1 - alfa / (2 * p), p - 2)
    return (p - 1) / math.sqrt(p) * math.sqrt(t * t / (p - 2 + t * t))


def mandel_h_formula(p: int, alfa: float) -> float:
    """h = (p-1) t / √(p (p-2+t²)), t bilateral α con p-2 gl."""
    t = stats.t.ppf(1 - alfa / 2, p - 2)
    return (p - 1) * t / math.sqrt(p * (p - 2 + t * t))


def mandel_k_formula(p: int, n: int, alfa: float) -> float:
    """k = √(p / (1 + (p-1)/F)), F = cuantil 1-α de F(n-1, (p-1)(n-1))."""
    f = stats.f.ppf(1 - alfa, n - 1, (p - 1) * (n - 1))
    return math.sqrt(p / (1 + (p - 1) / f))


# ---------------------------------------------------------------- consulta
def critico_cochran(p: int, n: int) -> dict:
    if p in COCHRAN and n in COCHRAN[p] and COCHRAN[p][n][0] is not None:
        c1, c5 = COCHRAN[p][n]
        return {"c1": c1, "c5": c5, "origen": f"{EDICION}, tabla 4"}
    if p >= 2 and n >= 2:
        return {"c1": round(cochran_formula(p, n, 0.01), 3), "c5": round(cochran_formula(p, n, 0.05), 3),
                "origen": f"Calculado por fórmula (fuera del rango de la tabla 4 de {EDICION})"}
    return {"c1": None, "c5": None, "origen": "No definido para p<2 o n<2"}


def critico_grubbs(p: int) -> dict:
    if p in GRUBBS:
        s1, s5, d1, d5 = GRUBBS[p]
        return {"simple1": s1, "simple5": s5, "doble1": d1, "doble5": d5, "origen": f"{EDICION}, tabla 5"}
    if p > 40:
        return {"simple1": round(grubbs_formula(p, 0.01), 3), "simple5": round(grubbs_formula(p, 0.05), 3),
                "doble1": None, "doble5": None,
                "origen": f"Simple calculado por fórmula (p>40); doble no disponible fuera de la tabla 5 de {EDICION}"}
    return {"simple1": None, "simple5": None, "doble1": None, "doble5": None, "origen": "No definido para p<3"}


def indicador_mandel(p: int, n: int | None, estadistico: str) -> dict:
    """Indicadores h (n=None) o k de las tablas 6 (1 %) y 7 (5 %)."""
    def de_tabla(nivel):
        fila = MANDEL[nivel].get(p)
        if fila is None:
            return None
        if estadistico == "h":
            return fila[0]
        return fila[n - 1] if n is not None and 2 <= n <= 10 else None
    v1, v5 = de_tabla(1), de_tabla(5)
    if v1 is not None and v5 is not None:
        return {"i1": v1, "i5": v5, "origen": f"{EDICION}, tablas 6 y 7"}
    if p >= 3 and (estadistico == "h" or (n or 0) >= 2):
        f = (lambda a: mandel_h_formula(p, a)) if estadistico == "h" else (lambda a: mandel_k_formula(p, n, a))
        return {"i1": round(f(0.01), 2), "i5": round(f(0.05), 2),
                "origen": f"Calculado por fórmula (fuera del rango de las tablas 6 y 7 de {EDICION})"}
    return {"i1": None, "i5": None, "origen": "No definido"}
